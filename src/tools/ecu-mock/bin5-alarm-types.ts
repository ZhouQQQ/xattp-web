function formatBin5AlarmLabel(value: number, meaning: string): string {
  const hex = value.toString(16).toUpperCase().padStart(2, "0");
  return `(0x${hex}) ${value} - ${meaning}`;
}

export const bin5AlarmTypeOptions: Bin5AlarmTypeOption[] = BIN5_ALARM_TYPE_ENTRIES.map(
  ([value, meaning]) => ({
    value,
    label: formatBin5AlarmLabel(value, meaning),
  }),
);

